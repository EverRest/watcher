<?php

declare(strict_types=1);

namespace Watcher\Mcp;

/**
 * FR-072/065: a PHP configuration snippet from validated, non-secret answers. Every credential is read from the environment
 * (`Env::...('WATCHER_...')`, or `env()` for Laravel); the variable list has a `secret` flag and no value. Strings are strictly
 * patterned by the tool schema, then quoted by the one function below. Deterministic: the same input gives the same bytes.
 */
final class ConfigGenerator
{
    /**
     * @param array{service: string, environment?: string, run_at: string, timezone?: string, host: string, source: string, notifier: string, state: string, stream_tags?: array<string, string>, level_mode?: string, env_names?: array<string, string>} $a
     * @return array{php_snippet: string, env_vars: list<array{name: string, purpose: string, secret: bool, required: bool}>, notes: list<string>, next_steps: list<string>}
     * @throws InvalidParams
     */
    public function generate(array $a): array
    {
        $names = $a['env_names'] ?? [];
        foreach (array_keys($names) as $logical) {
            if (!isset(SetupCatalog::ENV[$logical])) {
                throw new InvalidParams('invalid params: env_names');
            }
        }
        $tz = $a['timezone'] ?? 'UTC';
        if (!in_array($tz, \DateTimeZone::listIdentifiers(), true)) {
            throw new InvalidParams('invalid params: timezone');
        }
        $n = static fn (string $logical): string => $names[$logical] ?? SetupCatalog::ENV[$logical]['name'];
        // Env::* for every host: the shipped Laravel config reads it too, and `env()` would hand the strict boolean a string.
        $str = fn (string $logical, ?string $default = null): string => 'Env::string(' . self::q($n($logical)) . ($default === null ? '' : ', ' . self::q($default)) . ')';
        $int = fn (string $logical, int $default): string => 'Env::int(' . self::q($n($logical)) . ', ' . $default . ')';
        $float = fn (string $logical): string => 'Env::float(' . self::q($n($logical)) . ', 0.0)';
        $bool = 'Env::bool(' . self::q($n('enabled')) . ', false)';

        $L = [];
        $L[] = '<?php';
        $L[] = '';
        $L[] = 'declare(strict_types=1);';
        $L[] = '';
        $L[] = 'use Watcher\Config\Env;';
        $L[] = '';
        $L[] = '// Generated by watcher_generate_config. Every credential is read from the environment; no value is written here.';
        $L[] = 'return [';
        $L[] = "    'enabled' => $bool, // off until the variable is set in the environment that should run the watcher";
        $L[] = "    'service' => " . self::q($a['service']) . ',';
        if (isset($a['environment'])) {
            $L[] = "    'environment' => " . self::q($a['environment']) . ',';
        }
        $L[] = "    'schedule' => ['run_at' => " . self::q($a['run_at']) . ", 'timezone' => " . self::q($tz) . '],';
        $L[] = "    'source' => [";
        $L[] = "        'driver' => " . self::q($a['source']) . ',';
        if ($a['source'] === 'loki') {
            $L[] = "        'loki' => ['url' => " . $str('loki_url') . ", 'auth' => ['type' => 'bearer', 'token' => " . $str('loki_token') . ']],';
        } else {
            $L[] = "        'datadog' => ['site' => " . $str('dd_site', 'datadoghq.com') . ", 'api_key' => " . $str('dd_api_key') . ", 'app_key' => " . $str('dd_app_key') . '],';
        }
        $tags = $a['stream_tags'] ?? [];
        ksort($tags);
        $L[] = "        'stream_tags' => [" . implode(', ', array_map(static fn (string $k, string $v): string => self::q($k) . ' => ' . self::q($v), array_keys($tags), array_values($tags))) . '],';
        $L[] = "        'level_mode' => " . self::q($a['level_mode'] ?? 'text') . ',';
        $L[] = '    ],';
        $L[] = "    'analysis' => [";
        $L[] = "        'api_key' => " . $str('anthropic_key') . ',';
        $L[] = "        'models' => ['triage' => " . $str('model_triage') . ", 'analyze' => " . $str('model_analyze') . ", 'escalate' => " . $str('model_escalate') . '],';
        $L[] = '    ],';
        $L[] = "    'state' => " . match ($a['state']) {
            'redis' => "['driver' => 'redis', 'redis' => ['host' => " . $str('redis_host', '127.0.0.1') . ", 'port' => " . $int('redis_port', 6379) . ", 'password' => " . $str('redis_password') . ", 'database' => " . $int('redis_database', 0) . "]],",
            'pdo' => "['driver' => 'pdo', 'pdo' => ['dsn' => " . $str('db_dsn') . ", 'username' => " . $str('db_username') . ", 'password' => " . $str('db_password') . ']],',
            default => "['driver' => 'file', 'file' => ['path' => " . $str('state_path') . ']],',
        };
        $dest = match ($a['notifier']) {
            'slack' => "['driver' => 'slack', 'webhook' => " . $str('slack_webhook') . ']',
            'telegram' => "['driver' => 'telegram', 'bot_token' => " . $str('tg_token') . ", 'chat_id' => " . $str('tg_chat') . ']',
            default => "['driver' => 'discord', 'webhook' => " . $str('discord_webhook') . ']',
        };
        $L[] = "    'notify' => ['digest' => $dest],";
        $L[] = '];';
        $snippet = implode("\n", $L) . "\n";

        $logical = [...SetupCatalog::COMMON_VARS, ...SetupCatalog::SOURCE_VARS[$a['source']], ...SetupCatalog::NOTIFIER_VARS[$a['notifier']], ...SetupCatalog::STATE_VARS[$a['state']]];
        $notes = ['Every credential is read from the environment; define the listed variables in your secret store. The snippet holds no value.', 'The master switch stays off until ' . $n('enabled') . ' is set.'];
        if ($a['state'] === 'file') {
            $notes[] = 'The file state store is for a single runner: two schedulers must not share the directory.';
        }

        return ['php_snippet' => $snippet, 'env_vars' => SetupCatalog::vars($logical, $names), 'notes' => $notes, 'next_steps' => ['watcher_validate_config', 'watcher_rollout_check', 'watcher_first_day']];
    }

    private static function q(string $s): string
    {
        return "'" . strtr($s, ['\\' => '\\\\', "'" => "\\'"]) . "'";
    }
}
